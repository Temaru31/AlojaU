-- Tabla de planes (catálogo administrable).
CREATE TABLE IF NOT EXISTS planes_publicidad (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL CONSTRAINT uq_plan_nombre UNIQUE,
  dias INTEGER NOT NULL CONSTRAINT chk_plan_dias CHECK (dias > 0),
  precio_cop INTEGER NOT NULL CONSTRAINT chk_plan_precio CHECK (precio_cop >= 0),
  prioridad INTEGER NOT NULL CONSTRAINT chk_plan_prioridad CHECK (prioridad > 0),
  activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- Tabla de destacados comprados (historial: PENDIENTE vencido -> VENCIDO,
-- nunca se borra; ver job vencer_destacados()).
CREATE TABLE IF NOT EXISTS publicacion_destacados (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  publicacion_id BIGINT NOT NULL REFERENCES publicaciones(id) ON DELETE CASCADE,
  plan_id BIGINT NOT NULL REFERENCES planes_publicidad(id) ON DELETE RESTRICT,
  inicia TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  vence TIMESTAMPTZ NOT NULL,
  estado TEXT NOT NULL DEFAULT 'PENDIENTE'
    CONSTRAINT chk_destacado_estado CHECK (estado IN ('PENDIENTE','ACTIVO','VENCIDO','RECHAZADO')),
  pago_ref TEXT NULL,
  created_by BIGINT NULL REFERENCES usuarios(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT chk_destacado_vigencia CHECK (vence > inicia)
);

CREATE INDEX IF NOT EXISTS idx_destacados_pub_estado
  ON publicacion_destacados (publicacion_id, estado);
CREATE INDEX IF NOT EXISTS idx_destacados_estado_vence
  ON publicacion_destacados (estado, vence);
-- Un solo destacado ACTIVO por publicación (PENDIENTE/VENCIDO/RECHAZADO
-- múltiples sí permitidos: historial + reintentos).
CREATE UNIQUE INDEX IF NOT EXISTS uq_destacado_pub_activo
  ON publicacion_destacados (publicacion_id) WHERE estado = 'ACTIVO';

